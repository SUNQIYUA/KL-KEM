`timescale 1ns / 1ps

module tb_butterfly();

    // --------------------------------------------------------
    // 1. 信号声明
    // --------------------------------------------------------
    reg         clk;
    reg         rst_n;
    
    // 输入接口
    reg  [11:0] data_in_1;
    reg  [11:0] data_in_2;
    reg  [11:0] zeta;
    reg         din_vld;

    // 输出接口
    wire [11:0] post;
    wire [11:0] neg;
    wire        dout_vld;

    // --------------------------------------------------------
    // 2. 例化待测模块 (DUT)
    // --------------------------------------------------------
    butterfly #(
        .WIDTH(12),
        .Q(3329)
    ) uut (
        .clk        (clk),
        .rst        (rst_n),
        .data_in_1  (data_in_1),
        .data_in_2  (data_in_2),
        .zeta       (zeta),
        .din_vld    (din_vld),
        .post       (post),
        .neg        (neg),
        .done       (dout_vld)
    );

    // --------------------------------------------------------
    // 3. 时钟生成 (100MHz, 周期 10ns)
    // --------------------------------------------------------
    initial begin
        clk = 0;
        forever #5 clk = ~clk; 
    end

    // --------------------------------------------------------
    // 4. 驱动器 Task：流水线机枪射击
    // --------------------------------------------------------
    task feed_pipeline_data;
        input [11:0] test_x;
        input [11:0] test_y;
        input [11:0] test_zeta; // 【修改】这里直接输入真实的 zeta！
        begin
            data_in_1 <= test_x;
            data_in_2 <= test_y;
            zeta      <= test_zeta;
            din_vld   <= 1'b1;
            @(posedge clk);
        end
    endtask

    // --------------------------------------------------------
    // 5. 监视器 (Monitor)
    // --------------------------------------------------------
    integer out_cnt = 0;
    always @(posedge clk) begin
        if (rst_n && dout_vld) begin
            out_cnt = out_cnt + 1;
            $display("Time: %0t ns | 收到第 %0d 个结果 -> post: %4d, neg: %4d", $time, out_cnt, post, neg);
        end
    end

    // --------------------------------------------------------
    // 6. 主测试序列
    // --------------------------------------------------------
    initial begin
        rst_n     = 0;
        din_vld   = 0;
        data_in_1 = 0;
        data_in_2 = 0;
        zeta      = 0;

        #20;
        rst_n = 1;
        #20;
        @(posedge clk);

        $display("==================================================");
        $display("   Pipeline Butterfly (Barrett) Testbench Started");
        $display("==================================================");

        // ==========================================
        // 核心测试：连续背靠背 (Back-to-Back) 喂入 5 组数据
        // ==========================================
        $display("Time: %0t ns | 开始连续注入 5 组测试数据...", $time);
        
        // 数据 1: 常规测试
        // 计算: 2000 * 17 = 34000 -> 34000 % 3329 = 710
        // 期望: post = 1000 + 710 = 1710; neg = 1000 - 710 = 290
        feed_pipeline_data(1000, 2000, 17); 
        
        // 数据 2: 触发模约减边界
        // 计算: 1500 * 2000 = 3000000 -> 3000000 % 3329 = 571
        // 期望: post = 500 + 571 = 1071; neg = 500 - 571 + 3329 = 3258
        feed_pipeline_data(500,  1500, 2000); 
        
        // 数据 3: 极端零值测试
        // 期望: post = 0; neg = 0
        feed_pipeline_data(0,    0,    0);    
        
        // 数据 4: 极端最大值测试 (注意：Zeta位宽是12位，最大只能是4095，改为3328进行边界测试)
        // 计算: 3328 * 3328 = 11075584 -> 11075584 % 3329 = 31
        // 期望: post = (3328 + 31) % 3329 = 30; neg = (3328 - 31 + 3329) % 3329 = 3297
        feed_pipeline_data(3328, 3328, 3328); 
        
        // 数据 5: 随机常规数据
        // 计算: 567 * 890 = 504630 -> 504630 % 3329 = 1951
        // 期望: post = (1234 + 1951) % 3329 = 3185; neg = (1234 - 1951 + 3329) % 3329 = 2612
        feed_pipeline_data(1234, 567,  890);  

        // 停止喂数据
        din_vld   <= 1'b0;
        data_in_1 <= 12'hXXX; 
        data_in_2 <= 12'hXXX;
        zeta      <= 12'hXXX;
        
        $display("Time: %0t ns | 数据注入完毕，等待流水线排空 (Drain)...", $time);

        #200; 
        
        if (out_cnt == 5)
            $display("\n[PASS] 成功接收到 5 组数据！流水线吞吐率验证成功！");
        else
            $display("\n[FAIL] 丢失数据！期望接收 5 组，实际接收 %0d 组。", out_cnt);

        $display("==================================================");
        $finish;
    end

endmodule